#include "Piece.hpp"
#include "FPoint.hpp"
#include <cstddef>

auto Piece::get_shape() const -> Piece::Shape {
  // Piece shape/rotation data
  static constexpr Piece::Shape SHAPES[7][4]{
      // I
      {{{{-1, 0}, {0, 0}, {1, 0}, {2, 0}}},   // R0
       {{{0, -1}, {0, 0}, {0, 1}, {0, 2}}},   // R90
       {{{-2, 0}, {-1, 0}, {0, 0}, {1, 0}}},  // R180
       {{{0, 1}, {0, 0}, {0, -1}, {0, -2}}}}, // R90

      // O
      {{{{0, 0}, {1, 0}, {0, -1}, {1, -1}}},  // R0
       {{{0, 0}, {1, 0}, {0, -1}, {1, -1}}},  // R90
       {{{0, 0}, {1, 0}, {0, -1}, {1, -1}}},  // R180
       {{{0, 0}, {1, 0}, {0, -1}, {1, -1}}}}, // R270

      // T
      {{{{-1, 0}, {0, 0}, {1, 0}, {0, -1}}},  // R0
       {{{0, 1}, {0, 0}, {0, -1}, {1, 0}}},   // R90
       {{{-1, 0}, {0, 0}, {1, 0}, {0, 1}}},   // R180
       {{{0, 1}, {0, 0}, {0, -1}, {-1, 0}}}}, // R270

      // S
      {{{{-1, 0}, {0, 0}, {0, -1}, {1, -1}}},  // R0
       {{{0, -1}, {0, 0}, {1, 0}, {1, 1}}},    // R90
       {{{-1, 1}, {0, 1}, {0, 0}, {1, 0}}},    // R180
       {{{-1, -1}, {-1, 0}, {0, 0}, {0, 1}}}}, // R270

      // Z
      {{{{-1, -1}, {0, -1}, {0, 0}, {1, 0}}},  // R0
       {{{0, 1}, {0, 0}, {1, 0}, {1, -1}}},    // R90
       {{{-1, 0}, {0, 0}, {0, 1}, {1, 1}}},    // R180
       {{{-1, 1}, {-1, 0}, {0, 0}, {0, -1}}}}, // R270

      // J
      {{{{-1, 0}, {0, 0}, {1, 0}, {-1, -1}}}, // R0
       {{{0, 1}, {0, 0}, {0, -1}, {1, -1}}},  // R90
       {{{-1, 0}, {0, 0}, {1, 0}, {1, 1}}},   // R180
       {{{0, 1}, {0, 0}, {0, -1}, {-1, 1}}}}, // R270

      // L
      {{{{-1, 0}, {0, 0}, {1, 0}, {1, -1}}},    // R0
       {{{0, -1}, {0, 0}, {0, 1}, {1, 1}}},     // R90
       {{{-1, 0}, {0, 0}, {1, 0}, {-1, 1}}},    // R180
       {{{0, -1}, {0, 0}, {0, 1}, {-1, -1}}}}}; // R270

  auto shape = SHAPES[static_cast<size_t>(type)][static_cast<size_t>(rotation)];
  for (auto &p : shape)
    p = fpoint::add(p, pos);

  return shape;
}
